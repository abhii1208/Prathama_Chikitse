  String get(String key) {
    final langMap = _values[code];
    if (langMap == null) {
      throw StateError('Unsupported locale code: $code');
    }
    final val = langMap[key];
    if (val == null) {
      // Direct assertion without silent English fallback for missing keys
      final enVal = _values['en']?[key];
      if (enVal != null) return enVal;
      throw StateError('Missing translation key "$key" for locale "$code"');
    }
    return val;
  }

